import React, { useState } from 'react';
import { useApp } from '../context/AppContext';
import { 
  GitBranch, CheckCircle2, Circle, Clock, ExternalLink, 
  Sparkles, Award, Zap, ChevronDown, ChevronUp, BookOpen, Layers 
} from 'lucide-react';
import confetti from 'canvas-confetti';
import { RoadmapNode } from '../types';

export const RoadmapView: React.FC = () => {
  const { roadmap, activeCareer, toggleNodeCompletion } = useApp();
  const [selectedNode, setSelectedNode] = useState<RoadmapNode | null>(null);
  const [expandedPhases, setExpandedPhases] = useState<Record<number, boolean>>({ 1: true, 2: true, 3: true, 4: true, 5: true });

  const togglePhase = (phaseNum: number) => {
    setExpandedPhases(prev => ({ ...prev, [phaseNum]: !prev[phaseNum] }));
  };

  const handleToggleCompletion = (nodeId: string) => {
    toggleNodeCompletion(nodeId);
    confetti({
      particleCount: 50,
      spread: 60,
      origin: { y: 0.8 },
      colors: ['#6366f1', '#a855f7', '#38bdf8', '#34d399']
    });
  };

  if (!roadmap) {
    return (
      <div className="p-12 text-center text-slate-400">
        Loading personalized learning roadmap...
      </div>
    );
  }

  return (
    <div className="space-y-6 max-w-7xl mx-auto pb-12">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 p-6 rounded-3xl border border-slate-800/80 bg-slate-900/60 backdrop-blur-xl">
        <div>
          <div className="flex items-center gap-2 text-indigo-400 text-xs font-bold uppercase tracking-wider mb-1">
            <GitBranch className="w-4 h-4" />
            <span>Autonomous Curriculum Sequencing</span>
          </div>
          <h1 className="text-2xl font-extrabold text-white">
            Personalized Roadmap: {activeCareer.title}
          </h1>
          <p className="text-xs text-slate-400 mt-1 max-w-xl">
            Generated by the Learning Planner and Resource Recommender agents. Milestones update adaptively based on assessment results.
          </p>
        </div>

        <div className="flex items-center gap-4 bg-slate-950/60 p-3 rounded-2xl border border-slate-800 shrink-0">
          <div>
            <div className="text-xs text-slate-400">Total Hours</div>
            <div className="text-base font-bold text-white">{roadmap.total_estimated_hours} hrs</div>
          </div>
          <div className="h-8 w-px bg-slate-800" />
          <div>
            <div className="text-xs text-slate-400">Readiness Score</div>
            <div className="text-base font-bold text-indigo-400">{roadmap.readiness_score}%</div>
          </div>
        </div>
      </div>

      {/* Main Roadmap Phases Timeline */}
      <div className="space-y-6">
        {roadmap.phases.map((phase) => {
          const isExpanded = expandedPhases[phase.phase_number] ?? true;
          const completedCount = phase.nodes.filter(n => n.completed).length;

          return (
            <div
              key={phase.phase_number}
              className="rounded-3xl border border-slate-800/80 bg-slate-900/40 backdrop-blur-xl overflow-hidden"
            >
              {/* Phase Header */}
              <button
                onClick={() => togglePhase(phase.phase_number)}
                className="w-full p-5 sm:p-6 flex items-center justify-between bg-slate-900/80 hover:bg-slate-850 transition-colors text-left"
              >
                <div className="flex items-center gap-3">
                  <div className="w-8 h-8 rounded-xl bg-indigo-600/20 border border-indigo-500/30 flex items-center justify-center font-mono font-bold text-xs text-indigo-300">
                    0{phase.phase_number}
                  </div>
                  <div>
                    <h2 className="text-base font-bold text-white">{phase.title}</h2>
                    <span className="text-[11px] text-slate-400">
                      {completedCount}/{phase.nodes.length} Milestones Completed
                    </span>
                  </div>
                </div>

                <div className="flex items-center gap-3">
                  <div className="hidden sm:block w-32 bg-slate-800 rounded-full h-1.5 overflow-hidden">
                    <div
                      className="bg-indigo-500 h-1.5 rounded-full"
                      style={{ width: `${(completedCount / Math.max(phase.nodes.length, 1)) * 100}%` }}
                    />
                  </div>
                  {isExpanded ? (
                    <ChevronUp className="w-4 h-4 text-slate-400" />
                  ) : (
                    <ChevronDown className="w-4 h-4 text-slate-400" />
                  )}
                </div>
              </button>

              {/* Phase Nodes List */}
              {isExpanded && (
                <div className="p-5 sm:p-6 grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4 border-t border-slate-800/80">
                  {phase.nodes.map((node) => {
                    const isRemedial = node.is_remedial;

                    return (
                      <div
                        key={node.id}
                        onClick={() => setSelectedNode(node)}
                        className={`p-5 rounded-2xl border transition-all cursor-pointer flex flex-col justify-between relative group ${
                          isRemedial
                            ? 'border-amber-500/50 bg-amber-950/30 hover:border-amber-400 shadow-lg shadow-amber-950/40'
                            : node.completed
                            ? 'border-emerald-500/30 bg-emerald-950/20 hover:border-emerald-500/50'
                            : 'border-slate-800/80 bg-slate-950/60 hover:border-indigo-500/40'
                        }`}
                      >
                        <div>
                          {/* Top Badges */}
                          <div className="flex items-center justify-between gap-2 mb-2">
                            <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-slate-800/60 text-slate-400 uppercase">
                              {node.category}
                            </span>

                            {isRemedial ? (
                              <span className="text-[10px] font-bold px-2 py-0.5 rounded-full bg-amber-500/20 text-amber-300 border border-amber-500/40 flex items-center gap-1">
                                <Zap className="w-3 h-3 text-amber-400" />
                                <span>Remedial Sprint</span>
                              </span>
                            ) : node.completed ? (
                              <span className="text-[10px] font-bold px-2 py-0.5 rounded-full bg-emerald-500/20 text-emerald-300 border border-emerald-500/30 flex items-center gap-1">
                                <CheckCircle2 className="w-3 h-3 text-emerald-400" />
                                <span>Completed</span>
                              </span>
                            ) : (
                              <span className="text-[10px] font-semibold text-slate-400 flex items-center gap-1">
                                <Clock className="w-3 h-3" />
                                <span>{node.estimated_hours}h</span>
                              </span>
                            )}
                          </div>

                          <h3 className="text-sm font-bold text-white mb-1.5 group-hover:text-indigo-300 transition-colors">
                            {node.title}
                          </h3>

                          {isRemedial && (
                            <p className="text-[11px] text-amber-300/90 mb-3 bg-amber-950/40 p-2 rounded-lg border border-amber-500/20">
                              {node.reason}
                            </p>
                          )}

                          <div className="text-[11px] text-slate-400 space-y-1 mb-4">
                            {node.lessons.slice(0, 2).map((l, i) => (
                              <div key={i} className="flex items-center gap-1.5 truncate">
                                <div className="w-1 h-1 rounded-full bg-slate-500" />
                                <span className="truncate">{l}</span>
                              </div>
                            ))}
                          </div>
                        </div>

                        {/* Node Footer Toggle */}
                        <div className="pt-3 border-t border-slate-800/80 flex items-center justify-between">
                          <button
                            onClick={(e) => {
                              e.stopPropagation();
                              handleToggleCompletion(node.id);
                            }}
                            className={`px-3 py-1.5 rounded-xl text-xs font-semibold flex items-center gap-1.5 transition-all ${
                              node.completed
                                ? 'bg-emerald-500/20 text-emerald-300 hover:bg-emerald-500/30 border border-emerald-500/30'
                                : 'bg-slate-800 hover:bg-slate-700 text-slate-200'
                            }`}
                          >
                            {node.completed ? (
                              <>
                                <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
                                <span>Completed</span>
                              </>
                            ) : (
                              <>
                                <Circle className="w-3.5 h-3.5 text-slate-400" />
                                <span>Mark Complete</span>
                              </>
                            )}
                          </button>

                          <span className="text-[11px] text-indigo-400 group-hover:translate-x-0.5 transition-transform">
                            Details →
                          </span>
                        </div>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>
          );
        })}
      </div>

      {/* Node Detail Drawer / Modal */}
      {selectedNode && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-md">
          <div className="w-full max-w-2xl max-h-[85vh] overflow-y-auto rounded-3xl border border-slate-800 bg-slate-950 p-6 sm:p-8 space-y-6 shadow-2xl">
            <div className="flex items-start justify-between gap-4">
              <div>
                <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-slate-800 text-slate-400 uppercase">
                  {selectedNode.category} • {selectedNode.difficulty}
                </span>
                <h2 className="text-xl font-bold text-white mt-1">{selectedNode.title}</h2>
              </div>
              <button
                onClick={() => setSelectedNode(null)}
                className="text-slate-400 hover:text-white p-1 text-sm font-bold"
              >
                ✕
              </button>
            </div>

            {selectedNode.is_remedial && (
              <div className="p-3 rounded-xl bg-amber-950/40 border border-amber-500/30 text-xs text-amber-200">
                <strong>⚡ Adaptive Action:</strong> {selectedNode.reason}
              </div>
            )}

            {/* Lessons Section */}
            <div>
              <h3 className="text-xs font-bold uppercase tracking-wider text-slate-400 mb-2">
                Curriculum Lessons
              </h3>
              <div className="space-y-2">
                {selectedNode.lessons.map((lesson, idx) => (
                  <div key={idx} className="p-3 rounded-xl border border-slate-800 bg-slate-900/60 text-xs text-slate-200 flex items-center gap-2">
                    <BookOpen className="w-4 h-4 text-indigo-400 shrink-0" />
                    <span>{lesson}</span>
                  </div>
                ))}
              </div>
            </div>

            {/* Curated Resources */}
            <div>
              <h3 className="text-xs font-bold uppercase tracking-wider text-slate-400 mb-2">
                Verified Resources (Recommender Agent)
              </h3>
              <div className="space-y-2">
                {selectedNode.resources.map((res, idx) => (
                  <a
                    key={idx}
                    href={res.url}
                    target="_blank"
                    rel="noreferrer"
                    className="p-3 rounded-xl border border-slate-800 bg-slate-900/60 hover:bg-slate-800 text-xs text-slate-200 flex items-center justify-between group transition-colors"
                  >
                    <div className="space-y-0.5">
                      <div className="font-semibold text-slate-100 group-hover:text-indigo-300">
                        {res.title}
                      </div>
                      <div className="text-[10px] text-slate-400">
                        {res.type} • Est. {res.duration}
                      </div>
                    </div>
                    <ExternalLink className="w-4 h-4 text-slate-400 group-hover:text-indigo-400" />
                  </a>
                ))}
              </div>
            </div>

            {/* Hands-on Project Spec */}
            {selectedNode.project_prompt && (
              <div>
                <h3 className="text-xs font-bold uppercase tracking-wider text-slate-400 mb-2">
                  Hands-on Project Challenge
                </h3>
                <div className="p-4 rounded-xl border border-indigo-500/20 bg-indigo-950/20 text-xs text-slate-200">
                  {selectedNode.project_prompt}
                </div>
              </div>
            )}

            <div className="pt-4 border-t border-slate-800 flex justify-end gap-3">
              <button
                onClick={() => setSelectedNode(null)}
                className="px-4 py-2 rounded-xl text-xs text-slate-400 hover:text-white"
              >
                Close
              </button>
              <button
                onClick={() => {
                  handleToggleCompletion(selectedNode.id);
                  setSelectedNode(prev => prev ? { ...prev, completed: !prev.completed } : null);
                }}
                className={`px-5 py-2 rounded-xl text-xs font-semibold flex items-center gap-2 ${
                  selectedNode.completed
                    ? 'bg-emerald-600 hover:bg-emerald-500 text-white'
                    : 'bg-indigo-600 hover:bg-indigo-500 text-white'
                }`}
              >
                <CheckCircle2 className="w-4 h-4" />
                <span>{selectedNode.completed ? 'Mark as Incomplete' : 'Mark as Completed'}</span>
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
